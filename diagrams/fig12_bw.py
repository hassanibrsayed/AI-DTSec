def box(ax,x,y,w,h,txt,fc='white',ec='black',lw=1.6,fs=10.5,bold=False,ls='-'):
    ax.add_patch(FancyBboxPatch((x,y),w,h,boxstyle='round,pad=0,rounding_size=0.12',fc=fc,ec=ec,lw=lw,ls=ls))
    ax.text(x+w/2,y+h/2,txt,ha='center',va='center',fontsize=fs,fontweight='bold' if bold else 'normal',linespacing=1.35)
def arr(ax,p,q,lab=None,off=(0,0.12),cs='arc3',fs=11,ls='-',lw=1.5,both=False,ha='center'):
    ax.add_patch(FancyArrowPatch(p,q,arrowstyle='<|-|>' if both else '-|>',mutation_scale=13,lw=lw,color='#111',connectionstyle=cs,ls=ls,shrinkA=0,shrinkB=0))
    if lab: ax.text((p[0]+q[0])/2+off[0],(p[1]+q[1])/2+off[1],lab,ha=ha,va='center',fontsize=fs,style='italic')
